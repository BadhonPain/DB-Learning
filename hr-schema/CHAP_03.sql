-- CHAPTER 3 : Use of Oracle Single Row Functions

-- 1. CHARACTER FUNCTIONS

-- CASE COVERSION FUNCTIONS
SELECT (INITCAP(FIRST_NAME) || ' ' || LOWER(LAST_NAME)) NAME, UPPER(JOB_ID) JOB
FROM HR.EMPLOYEES;

SELECT *
FROM HR.DEPARTMENTS
WHERE  UPPER(DEPARTMENT_NAME) LIKE '%SALE%';
-- OR,
SELECT *
FROM HR.DEPARTMENTS
WHERE  LOWER(DEPARTMENT_NAME) LIKE '%sale%';

SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) NAME, JOB_ID
FROM HR.EMPLOYEES
WHERE INSTR(JOB_ID,'CLERK') > 0;

SELECT (SUBSTR(FIRST_NAME, 1, 1) || SUBSTR(LAST_NAME, 1, 1) || '.') ABBR, SALARY
FROM HR.EMPLOYEES;

SELECT INITCAP(CONCAT(TRIM(FIRST_NAME),' ',TRIM(LAST_NAME))) NAME, LPAD(SALARY, 6 ,0) ROUNDED_SALARY
FROM HR.EMPLOYEES;

