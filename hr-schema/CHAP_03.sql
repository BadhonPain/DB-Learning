-- 2. NUMBER FUNCTIONS

SELECT FIRST_NAME, ROUND(SALARY/1000, 2) "SALARY (IN THOUSAND)"
FROM HR.EMPLOYEES
WHERE INSTR(JOB_ID, 'CLERK') > 0;

SELECT FIRST_NAME, ROUND((SYSDATE - HIRE_DATE)/7, 4) "WEEKS EMPLOYED"
FROM HR.EMPLOYEES
WHERE INSTR(JOB_ID, 'CLERK') > 0;

SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) NAME, 
            (TRUNC(SALARY/1000, 0) || ' THOUSANDS ' || 
            TRUNC(MOD(SALARY, 1000)/100, 0) || ' HUNDREDS ' || 
            MOD(SALARY, 100) || ' TAKA ONLY ') "SALARY (IN WRITING)", SALARY
FROM HR.EMPLOYEES;

