-- CHAPTER 2 : RETRIEVE DATA FROM DB TABLES
-- 1. Selecting Data using basic SELECT statement

-- Alias of a column
SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY*12 ANNUAL_SALARY
FROM HR.EMPLOYEES;

-- Space containing alias
SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY*12 "ANNUAL SALARY"
FROM HR.EMPLOYEES;

-- Checking null values
SELECT FIRST_NAME, COMMISSION_PCT
FROM HR.EMPLOYEES;

-- Any arithmatic operation on null values simply returns null
SELECT FIRST_NAME, (SALARY + SALARY*COMMISSION_PCT) "FINAL SALARY"
FROM HR.EMPLOYEES;

-- Concatenation operation ||
SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME", SALARY
FROM HR.EMPLOYEES;

-- Use of DISTINCT keyword
SELECT DISTINCT JOB_ID
FROM HR.EMPLOYEES;

-- Use of DISTINCT to remove duplicate tuples
SELECT DISTINCT DEPARTMENT_ID, JOB_ID
FROM HR.EMPLOYEES;

-- Use of DESCRIBE statement
DESCRIBE HR.EMPLOYEES;

