-- 4. Functions for manipulating NULL values

-- NVL FUNCTION

SELECT LAST_NAME, NVL(COMMISSION_PCT, 0) "COMMISSION_PCT"
FROM HR.EMPLOYEES;

-- Check whose COMMISSION_PCT IS NULL
SELECT LAST_NAME, COMMISSION_PCT
FROM HR.EMPLOYEES
WHERE NVL(COMMISSION_PCT, -1) = -1;

SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) "NAME", (SALARY + SALARY*NVL(COMMISSION_PCT, 0)) "SALARY"
FROM HR.EMPLOYEES;

-- Practice 3.4

