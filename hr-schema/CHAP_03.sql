-- 5. Data Type Conversion Functions 

-- Explicit type conversion: TO_CHAR function 
SELECT LAST_NAME, TO_CHAR(HIRE_DATE, 'DD MON, YYYY') "JOINING DATE"
FROM HR.EMPLOYEES;

SELECT LAST_NAME, TO_CHAR(HIRE_DATE, 'Ddspth MONTH, YYYY') "JOINING DATE"
FROM HR.EMPLOYEES;

-- Explicit type conversion: TO_NUMBER function 
SELECT STREET_ADDRESS, POSTAL_CODE 
FROM HR.LOCATIONS 
ORDER BY POSTAL_CODE ASC ; 
-- WON'T GIVE THE EXPECTED OUTPUT, CORRECT :
SELECT STREET_ADDRESS, POSTAL_CODE
FROM HR.LOCATIONS
WHERE REGEXP_LIKE(POSTAL_CODE, '^[0-9]+$')
ORDER BY TO_NUMBER(POSTAL_CODE);

-- Explicit type conversion: TO_DATE function 
SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) "NAME", TO_CHAR(HIRE_DATE, 'DD-MON-YYYY') "HIRE DATE"
FROM HR.EMPLOYEES
WHERE HIRE_DATE < TO_DATE('01-JAN-2017', 'DD-MON-YYYY')
ORDER BY HIRE_DATE ASC;

