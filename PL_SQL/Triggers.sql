-- 3. run when update is performed on the CGPA column.
CREATE OR REPLACE TRIGGER HW3
AFTER UPDATE 
OF CGPA 
ON STUDENTS 
DECLARE
BEGIN
    DBMS_OUTPUT.PUT_LINE('HELLO WORLD AFTER UPDATING ON CGPA COLUMN!');
END ;
/

UPDATE STUDENTS SET CGPA = CGPA + 0.2
WHERE CGPA < 3.50;
UPDATE STUDENTS SET STUDENT_NAME = 'BADHON PAIN'  -- TRIGGER WON'T GET CALLED FOR THAT STATEMENT
WHERE STUDENT_NAME  LIKE 'Ahmed Nahiyan';


-- 4. this trigger will run N times if N rows are affected by the SQL statement.
CREATE OR REPLACE TRIGGER HW4
AFTER UPDATE 
OF CGPA 
ON STUDENTS 
FOR EACH ROW
DECLARE
BEGIN
    DBMS_OUTPUT.PUT_LINE('THIS ROW IS UPDATED !');
END ;
/

UPDATE STUDENTS SET CGPA = CGPA + 0.2
WHERE CGPA < 3.50;
UPDATE STUDENTS SET STUDENT_NAME = 'SHAHRUKH KHAN'  -- TRIGGER WON'T GET CALLED FOR THAT STATEMENT
WHERE STUDENT_NAME  LIKE 'Fahim Hasan';

