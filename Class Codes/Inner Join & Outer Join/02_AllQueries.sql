USE class_codes;

-- 01: INNER JOIN EXAMPLE
SELECT *
FROM PCFORJOIN AS P INNER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- 02: LEFT OUTER JOIN EXMAPLE
SELECT *
FROM PCFORJOIN AS P LEFT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- 03: RIGHT OUTER JOIN EXMAPLE
SELECT *
FROM PCFORJOIN AS P RIGHT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- 04: FULL OUTER JOIN EXMAPLE
SELECT *
FROM PCFORJOIN AS P FULL OUTER JOIN LAPTOPFORJOIN AS L         -- PERFECT FOR ORACLE, DOESN'T SUPPORT IN MYSQL (DO UNION OF LEFT AND RIGHT OUTER JOIN)
ON P.MAKER = L.MAKER;

-- IN MYSQL :
SELECT *
FROM PCFORJOIN AS P LEFT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
UNION
SELECT *
FROM PCFORJOIN AS P RIGHT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- 05: Find all manufacturers that sell both PC and Laptop
SELECT DISTINCT P.MAKER
FROM PCFORJOIN AS P INNER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- 06: Find all manufacturers that make PCs but not Laptops
SELECT DISTINCT P.MAKER
FROM PCFORJOIN AS P LEFT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
WHERE L.MAKER IS NULL
AND P.MAKER IS NOT NULL;

-- 07: Find all manufacturers that make Laptops but not PCs
SELECT DISTINCT L.MAKER
FROM PCFORJOIN AS P RIGHT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
WHERE P.MAKER IS NULL
AND L.MAKER IS NOT NULL;

-- 08: Find all manufacturers that make either Laptop or PC or both
SELECT DISTINCT P.MAKER
FROM PCFORJOIN AS P FULL OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
WHERE P.MAKER IS NOT NULL
UNION 
SELECT DISTINCT L.MAKER
FROM PCFORJOIN AS P FULL OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
WHERE L.MAKER IS NOT NULL;

-- IN MYSQL :
SELECT P.MAKER
FROM PCFORJOIN AS P LEFT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER
UNION
SELECT L.MAKER
FROM PCFORJOIN AS P RIGHT OUTER JOIN LAPTOPFORJOIN AS L
ON P.MAKER = L.MAKER;

-- SOLVE 06 USING RIGHT OUTER JOIN
SELECT DISTINCT P.MAKER
FROM LAPTOPFORJOIN AS L RIGHT OUTER JOIN PCFORJOIN AS P
ON P.MAKER = L.MAKER
WHERE L.MAKER IS NULL
AND P.MAKER IS NOT NULL;

-- SOLVE 07 USING LEFT OUTER JOIN
SELECT DISTINCT L.MAKER
FROM LAPTOPFORJOIN AS L LEFT OUTER JOIN PCFORJOIN AS P
ON P.MAKER = L.MAKER
WHERE P.MAKER IS NULL
AND L.MAKER IS NOT NULL;