-- find whether employee numbered 100 has worked 10 years or more. Let us call this procedure IS_SENIOR_EMPLOYEE.
SET SERVEROUTPUT ON;

CREATE OR REPLACE PROCEDURE IS_HE_SENIOR_EMPLOYEE IS 
    J_DATE DATE;
    YEARS  NUMBER;
BEGIN
    SELECT HIRE_DATE INTO J_DATE
    FROM HR.EMPLOYEES
    WHERE EMPLOYEE_ID = 100;
    
    YEARS := ROUND(MONTHS_BETWEEN(SYSDATE, J_DATE)/12);
    IF YEARS >= 10 THEN 
        DBMS_OUTPUT.PUT_LINE('THE WORKER WITH ID NO 100 WORKED 10 YEARS OR MORE.');
    ELSE DBMS_OUTPUT.PUT_LINE('THE WORKER WITH ID NO 100 DID NOT WORK 10 YEARS OR MORE.');
    END IF;
END;
/

DECLARE 

BEGIN 
    IS_HE_SENIOR_EMPLOYEE;
END;
/


