-- 3. DATE FUNCTIONS

-- Use of SYSDATE
SELECT LAST_NAME, (SYSDATE - HIRE_DATE)/7 "WEEKS EMPLOYED" 
FROM HR.EMPLOYEES 
WHERE DEPARTMENT_ID = 80 ;

-- Date Arithmatic

-- VALID OPERATIONS:
-- DATE - DATE
-- DATE + NUMBER
-- DATE - NUMBER

-- DATE Manipulation FUNCTIONS:

SELECT LAST_NAME, MONTHS_BETWEEN(SYSDATE, HIRE_DATE) MON_EMPLOYED 
FROM HR.EMPLOYEES ; 

-- Practice 3.3

