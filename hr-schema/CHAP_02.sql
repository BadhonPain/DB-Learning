-- 2.SELECT statement with WHERE clause

SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME", (SALARY+SALARY*COMMISSION_PCT) "FULL SALARY"
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL;

SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME"
FROM HR.EMPLOYEES
WHERE HIRE_DATE > '02-MAR-2016';

-- Use of BETWEEN _ AND _ operator
SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME"
FROM HR.EMPLOYEES
WHERE HIRE_DATE BETWEEN '01-JAN-2015' AND '01-JAN-2016' ;

-- Use of IN operator
SELECT FIRST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME IN ('Chung', 'Pain', 'Bates', 'Austin');

SELECT FIRST_NAME, SALARY 
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (10,20,30,40,50);

-- Joining multiple conditions
SELECT LAST_NAME, SALARY 
FROM HR.EMPLOYEES 
WHERE DEPARTMENT_ID <> 80 AND  
        (SALARY > 5000 OR COMMISSION_PCT IS NOT NULL) ;

SELECT LAST_NAME, SALARY 
FROM HR.EMPLOYEES 
WHERE (DEPARTMENT_ID = 80 AND SALARY > 5000) OR 
         COMMISSION_PCT IS NOT NULL  ; 
    
-- Pattern matching using LIKE operator

SELECT LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '%a_s';

-- Coparing with NULL values

SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME"
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT = NULL;
-- won't give the result as expected
-- correct way :
SELECT (FIRST_NAME || ' ' || LAST_NAME) "FULL NAME"
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NULL;

